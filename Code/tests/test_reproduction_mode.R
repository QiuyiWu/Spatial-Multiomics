# Integration checks use a temporary reproduction folder and leave Data/ untouched.
here::i_am('README.md')
source(here::here('Code','pipeline_paths.R'))
reference <- list.files(here::here('Data'),full.names=TRUE)
before <- tools::md5sum(reference)
run <- tempfile('proteinfix-reproduction-');dir.create(run)
options(proteinfix.mode='reproduce',proteinfix.run_dir=run,proteinfix.rebuild_graph=FALSE)
stopifnot(dirname(proteinfix_output('test.rds'))==file.path(normalizePath(run),'Data'))
saveRDS('new output',proteinfix_output('test.rds'))
stopifnot(readRDS(proteinfix_input('test.rds'))=='new output')
unlink(file.path(run,'Data','test.rds'))
options(proteinfix.mode='update')
stopifnot(identical(proteinfix_output('a26_score.RData'),here::here('Data','a26_score.RData')))
options(proteinfix.mode='reproduce')
options(proteinfix.run_dir=here::here())
stopifnot(inherits(try(proteinfix_output('test.rds'),silent=TRUE),'try-error'))
options(proteinfix.run_dir=run)
pdf(file.path(run,'diagnostics.pdf'))
for(animal in c('A26','A27')) {
  e <- new.env(parent=globalenv())
  sys.source(here::here('Code',animal,'HeldoutPreprocessing.R'),e)
  filename <- paste0('Heldout_Updated_',tolower(animal),'.xlsx')
  stopifnot(identical(proteinfix_input(filename),file.path(normalizePath(run),'Data',filename)))
  expected <- as.data.frame(readxl::read_xlsx(here::here('Data',filename)))
  actual <- as.data.frame(readxl::read_xlsx(proteinfix_input(filename)))
  stopifnot(isTRUE(all.equal(expected,actual,tolerance=1e-10)))
  code <- readLines(here::here('Code',animal,'CombineClustering.R'))
  end <- grep('^# C5\\.',code)[1]-2L
  eval(parse(text=code[seq_len(end)]),e)
  selected <- paste0(tolower(animal),'.RData')
  original <- new.env();load(here::here('Data',selected),original)
  generated <- new.env();load(proteinfix_input(selected),generated)
  stopifnot(isTRUE(all.equal(as.list(original),as.list(generated),tolerance=1e-10)))
  # Load graph via helper without invoking adegenet; changed coordinates must fail.
  g <- new.env();load(here::here('Data',paste0('sPCA_',tolower(animal),'metCluster.RData')),g)
  graph <- g$spca_delaunay_metCluster
  cluster <- new.env();load(here::here('Data',paste0(animal,'_PChclust.RData')),cluster)
  scores <- get(paste0(tolower(animal),'.met.cluster'),cluster)$score[rownames(graph$li),,drop=FALSE]
  filename <- paste0('sPCA_',tolower(animal),'metCluster.RData')
  stopifnot(identical(proteinfix_graph(filename,scores,graph$xy)$lw$neighbours,graph$lw$neighbours))
  xy <- graph$xy;xy[1,1] <- xy[1,1]+1
  stopifnot(inherits(try(proteinfix_graph(filename,scores,xy),silent=TRUE),'try-error'))
  options(proteinfix.rebuild_graph=TRUE)
  rebuilt <- proteinfix_graph(filename,scores,graph$xy)
  stopifnot(identical(rebuilt$lw$neighbours,graph$lw$neighbours),
            file.exists(file.path(run,'Data',filename)))
  options(proteinfix.rebuild_graph=FALSE)
  # Exercise the C6 Rmd's actual save expression with the existing fitted model.
  fitted <- new.env();load(here::here('Data',paste0(tolower(animal),'_score.RData')),fitted)
  lines <- readLines(here::here('Code',animal,paste0(animal,'_analysis_sCCA_laplacians.Rmd')))
  save_line <- grep('^save\\(scca_res,',lines,value=TRUE)
  stopifnot(length(save_line)==1L)
  eval(parse(text=save_line),fitted)
  message(animal,': C3/C4 match; graph load/rebuild and C6 output routing pass')
}
dev.off()
source(here::here('Code','compare_reproduction.R'))
stopifnot(all(report$result=='Match'))
stopifnot(identical(before,tools::md5sum(reference)))
message('All reference files unchanged. Test outputs: ',run)
